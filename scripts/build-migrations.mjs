/**
 * Builds supabase/all-migrations.sql - every migration, in order, in one
 * file.
 *
 * Run: npm run db:migrations
 *
 * The Supabase SQL editor runs a pasted script in a single transaction, so a
 * single failing statement rolls the whole thing back. Every migration in
 * this folder is written to be re-runnable (create table if not exists, drop
 * policy if exists before create policy, ...), so this combined file can be
 * pasted into a project that already has some - or all - of the schema
 * applied. It is what to use when a migration run stops halfway with
 * "policy ... already exists" (SQLSTATE 42710).
 *
 * The seed (supabase/seed.sql) is NOT part of this file: the seed truncates
 * and re-inserts the content tables.
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(process.cwd());
const dir = path.join(root, "supabase", "migrations");
const out = path.join(root, "supabase", "all-migrations.sql");

const files = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

if (!files.length) {
  console.error("No migrations found in supabase/migrations");
  process.exit(1);
}

const header = `-- ============================================================
-- ANIMELK - every migration in one file
--
-- GENERATED by scripts/build-migrations.mjs - do not edit by hand.
-- Run "npm run db:migrations" after changing a migration.
--
-- Paste this whole file into the Supabase SQL editor (SQL editor -> New
-- query -> paste -> Run). Every statement in it is safe to run again:
-- tables and indexes are created "if not exists" and every policy is
-- dropped before it is created, so pasting this a second time (or on a
-- project that already has part of the schema) succeeds instead of
-- failing with "policy ... already exists" (SQLSTATE 42710).
--
-- It does NOT include supabase/seed.sql, which truncates and re-inserts
-- the content tables.
-- ============================================================

`;

const body = files
  .map((f) => {
    const sql = fs.readFileSync(path.join(dir, f), "utf8").trimEnd();
    return `-- ------------------------------------------------------------\n-- ${f}\n-- ------------------------------------------------------------\n${sql}\n`;
  })
  .join("\n");

fs.writeFileSync(out, header + body);
console.log(`Wrote supabase/all-migrations.sql (${files.length} migrations, ${(header + body).split("\n").length} lines)`);
